"""Shared logic to validate a customization and turn it into API output (used by designs and orders)."""
from fastapi import HTTPException
from sqlalchemy import select, update
from sqlalchemy.orm import Session

from ..models import Phone, SheetSticker, Sticker, StickerSheet, User
from ..schemas import DesignIn, PhoneOut, PlacedSticker, StickerOut


def _bad(msg: str) -> HTTPException:
    return HTTPException(422, msg)


def _claim_guest_items(db: Session, user: User, body: DesignIn) -> None:
    """Things a visitor created before onboarding (user_id / created_by NULL) are attached to the user
    who now proves they own the session (the random session_id generated by the browser)."""
    if body.session_id:
        db.execute(
            update(Sticker)
            .where(Sticker.user_id.is_(None), Sticker.session_id == body.session_id)
            .values(user_id=user.id)
        )
    phone = db.get(Phone, body.phone_id)
    if phone and phone.custom and phone.created_by is None:
        phone.created_by = user.id


def load_sheet_stickers(db: Session, ids: set[str]) -> dict[str, SheetSticker]:
    """Sheet stickers that can be used by NEW designs: they must belong to a currently published sheet."""
    if not ids:
        return {}
    stmt = (
        select(SheetSticker)
        .join(StickerSheet, SheetSticker.sheet_id == StickerSheet.id)
        .where(SheetSticker.id.in_(ids), StickerSheet.status == "published")
    )
    return {s.id: s for s in db.scalars(stmt)}


def validate_design(db: Session, user: User, body: DesignIn) -> tuple[Phone, list[Sticker], dict[str, SheetSticker]]:
    _claim_guest_items(db, user, body)
    phone = db.get(Phone, body.phone_id)
    if not phone or (phone.custom and phone.created_by != user.id):
        raise _bad("Unknown phone model.")
    # The color format is already validated and normalized to '#rrggbb' by DesignIn (any color is allowed).
    if body.case_type == "silicone" and not body.color:
        raise _bad("Choose a silicone color.")
    ids = set(body.upload_ids) | {s.ref_id for s in body.stickers if s.kind == "upload"}
    uploads = list(db.scalars(select(Sticker).where(Sticker.id.in_(ids), Sticker.user_id == user.id))) if ids else []
    if len(uploads) != len(ids):
        raise _bad("A sticker in this design does not exist anymore. Please upload it again.")
    sheet_ids = {s.ref_id for s in body.stickers if s.kind == "sheet"}
    sheet_stickers = load_sheet_stickers(db, sheet_ids)
    if len(sheet_stickers) != len(sheet_ids):
        raise _bad("A sticker from the sticker sheet is no longer available. Please remove it from your design.")
    return phone, uploads, sheet_stickers


def render(design_fields: dict, phone: Phone, uploads: list[Sticker], url_for, sheet_srcs: dict[str, str] | None = None) -> dict:
    """Builds the camelCase payload: placed stickers get their image URL, uploads are listed.
    sheet_srcs maps sheet-sticker ids to the URL to show (live file for designs, frozen copy for orders)."""
    sheet_srcs = sheet_srcs or {}
    by_id = {u.id: u for u in uploads}
    placed = []
    for s in design_fields["stickers"]:
        s = PlacedSticker.model_validate(s)
        if s.kind == "upload" and s.ref_id in by_id:
            s = s.model_copy(update={"src": url_for(by_id[s.ref_id])})
        elif s.kind == "sheet" and s.ref_id in sheet_srcs:
            s = s.model_copy(update={"src": sheet_srcs[s.ref_id]})
        else:
            s = s.model_copy(update={"src": None})
        placed.append(s)
    ordered_uploads = [by_id[i] for i in design_fields["upload_ids"] if i in by_id]
    return {
        "phone": PhoneOut.model_validate(phone),
        "stickers": placed,
        "uploads": [
            StickerOut(id=u.id, name=u.original_name, src=url_for(u), ar=u.aspect,
                       kept_background=u.filename.lower().endswith(".webp"))
            for u in ordered_uploads
        ],
    }